function get_current_lang(): string {
    if (isset($_GET['lang']) && in_array($_GET['lang'], ['en', 'ur'], true)) {
        $_SESSION['app_lang'] = $_GET['lang'];
    }
    return $_SESSION['app_lang'] ?? 'en';
}

function is_rtl(): bool {
    return get_current_lang() === 'ur';
}

